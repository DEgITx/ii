// `ii ops`: lists the operation set; `--markdown` produces the OpSet reference (docs/opset.md).
#include <ii/opset.h>

#include "args.h"
#include "commands.h"

#include <cstdio>
#include <string>
#include <vector>

namespace ii::cli {

namespace {

constexpr const char* kUsage = R"(Usage: ii ops [options] [name...]

Lists the operations of the OpSet with their inputs, outputs and attributes.

Options:
  --markdown          Print the OpSet reference in Markdown (docs/opset.md)
  --help              Show this help
)";

std::string signature(const OperationInfo& op) {
    std::string text = op.name + "(";
    for (std::size_t i = 0; i < op.inputs.size(); ++i) {
        text += (i > 0 ? ", " : "") + op.inputs[i];
    }
    text += ") -> ";
    for (std::size_t i = 0; i < op.outputs.size(); ++i) {
        text += (i > 0 ? ", " : "") + op.outputs[i];
    }
    return text;
}

std::string attribute_text(const AttributeInfo& attr) {
    std::string text = attr.name + ": " + attr.kind;
    text += attr.default_value ? " = " + *attr.default_value : " (required)";
    return text;
}

void print_markdown(const std::vector<OperationInfo>& ops) {
    std::printf("# ii OpSet v1\n\n");
    std::printf("> Generated by `ii ops --markdown` from the operation schemas (`src/ops`). Do not edit.\n\n");
    std::printf("Conventions: the IR is strictly typed (inputs of arithmetic operations share one dtype; importers "
                "insert `cast`), binary elementwise operations broadcast with numpy rules, negative axes count from "
                "the back. Optional inputs are marked `?`, variadic ones `...`. Composite operations have a "
                "decomposition into primitives; backends may implement them natively.\n\n");
    std::string category;
    for (const OperationInfo& op : ops) {
        if (op.category != category) {
            category = op.category;
            std::printf("## %s\n\n", category.c_str());
        }
        std::printf("### `%s`%s\n\n", op.name.c_str(), op.composite ? " (composite)" : "");
        std::printf("`%s`\n\n%s\n\n", signature(op).c_str(), op.doc.c_str());
        if (!op.attributes.empty()) {
            std::printf("| Attribute | Kind | Default |\n|---|---|---|\n");
            for (const AttributeInfo& attr : op.attributes) {
                std::printf("| `%s` | %s | %s |\n", attr.name.c_str(), attr.kind.c_str(),
                            attr.default_value ? ("`" + *attr.default_value + "`").c_str() : "required");
            }
            std::printf("\n");
        }
    }
}

}  // namespace

int run_ops(const std::vector<std::string>& args) {
    auto parsed = Args::parse(args, {"markdown", "help"}, {});
    if (!parsed.ok()) {
        std::fprintf(stderr, "ii ops: %s\n\n%s", std::string(parsed.status().message()).c_str(), kUsage);
        return 2;
    }
    if (parsed->flag("help")) {
        std::printf("%s", kUsage);
        return 0;
    }
    std::vector<OperationInfo> ops = list_operations();
    if (!parsed->positionals().empty()) {
        std::vector<OperationInfo> selected;
        for (const std::string& name : parsed->positionals()) {
            bool found = false;
            for (const OperationInfo& op : ops) {
                if (op.name == name) {
                    selected.push_back(op);
                    found = true;
                }
            }
            if (!found) {
                std::fprintf(stderr, "ii ops: unknown operation '%s'\n", name.c_str());
                return 1;
            }
        }
        ops = std::move(selected);
    }
    if (parsed->flag("markdown")) {
        print_markdown(ops);
        return 0;
    }
    for (const OperationInfo& op : ops) {
        std::printf("%-16s %s%s\n", op.name.c_str(), signature(op).c_str(), op.composite ? "  [composite]" : "");
        if (!parsed->positionals().empty()) {
            std::printf("  %s\n", op.doc.c_str());
            for (const AttributeInfo& attr : op.attributes) {
                std::printf("  %s\n", attribute_text(attr).c_str());
            }
        }
    }
    return 0;
}

}  // namespace ii::cli
