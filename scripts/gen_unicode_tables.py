"""Generates src/llm/unicode_data.cpp: code point ranges of the Unicode general categories L (letters) and N
(numbers), used by the pre-tokenizers of byte-level BPE tokenizers (\\p{L}, \\p{N} in their split patterns).

Usage:
    python scripts/gen_unicode_tables.py            # writes src/llm/unicode_data.cpp
    python scripts/gen_unicode_tables.py --check    # fails if the committed file is out of date

The data comes from Python's unicodedata module; the Unicode version is recorded in the file. The output is formatted
with clang-format (on PATH, or --clang-format), the version CI pins.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "llm" / "unicode_data.cpp"


def ranges(predicate) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        inside = predicate(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            result.append((start, cp - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def generate() -> str:
    letters = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    numbers = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("N"))
    lines = [
        "// SPDX-License-Identifier: MIT",
        f"// Generated by scripts/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}. Do not edit.",
        '#include "llm/unicode.h"',
        "",
        "namespace ii::llm::detail {",
        "",
    ]
    for name, table in (("kLetterRanges", letters), ("kNumberRanges", numbers)):
        lines.append(f"const CodepointRange {name}[] = {{")
        row = []
        for start, end in table:
            row.append(f"{{0x{start:X}, 0x{end:X}}},")
            if len(row) == 6:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("};")
        lines.append(f"const std::size_t {name}Count = sizeof({name}) / sizeof({name}[0]);")
        lines.append("")
    lines.append("}  // namespace ii::llm::detail")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed file is out of date")
    parser.add_argument("--clang-format", default="clang-format", help="clang-format executable")
    args = parser.parse_args()
    text = subprocess.run([args.clang_format, f"--assume-filename={OUTPUT}"], input=generate(), capture_output=True,
                          text=True, encoding="utf-8", check=True, cwd=ROOT).stdout
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/gen_unicode_tables.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
